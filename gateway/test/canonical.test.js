test('categories', () => {
  assert.equal(categoryFor('Мочевина в сыворотке'), 'blood');
  assert.equal(categoryFor('Лейкоциты полуколичественно'), 'urine');
  assert.equal(categoryFor('Цвет'), 'urine');
  assert.equal(categoryFor('Удельный вес'), 'urine');
  assert.equal(categoryFor('PH'), 'urine');
  assert.equal(categoryFor('Гемоглобин'), 'blood');
  assert.deepEqual(classify('Белок полуколичественно'), { key: 'U-PRO', category: 'urine' });
});

test('catalog shape', () => {
  const c = catalog();
  assert.ok(c.length > 30);
  assert.deepEqual(keyKeys(), ['ALT', 'AST', 'CREA', 'HGB', 'WBC', 'NEUT#', 'PLT', 'TSH']);
  const keys = new Set(c.map((e) => e.key));
  assert.equal(keys.size, c.length, 'keys are unique');
});
